-- Esquema del checkout (spec 004). Las órdenes son registros históricos: guardan copia del
-- nombre, la categoría y el precio unitario, así que no dependen de cambios posteriores del
-- catálogo. El identificador de la orden es un UUID generado en el servidor.

CREATE TABLE coupons (
    code       VARCHAR(50)   PRIMARY KEY,
    percent    DECIMAL(5, 2) NOT NULL,
    valid_from DATE          NOT NULL,
    valid_to   DATE          NOT NULL,
    CONSTRAINT ck_coupons_percent CHECK (percent > 0 AND percent <= 100),
    CONSTRAINT ck_coupons_dates CHECK (valid_from <= valid_to)
);

CREATE TABLE orders (
    id                         UUID           PRIMARY KEY,
    user_id                    BIGINT         NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE NOT NULL,
    original_subtotal          DECIMAL(12, 2) NOT NULL,
    total_discount             DECIMAL(12, 2) NOT NULL,
    total                      DECIMAL(12, 2) NOT NULL,
    effective_discount_percent DECIMAL(5, 2)  NOT NULL,
    cap_applied                BOOLEAN        NOT NULL,
    coupon_code                VARCHAR(50),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   UUID           NOT NULL,
    product_id BIGINT         NOT NULL,
    name       VARCHAR(120)   NOT NULL,
    category   VARCHAR(20)    NOT NULL,
    unit_price DECIMAL(10, 2) NOT NULL,
    quantity   INT            NOT NULL,
    line_total DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE TABLE order_discounts (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID           NOT NULL,
    type     VARCHAR(20)    NOT NULL,
    label    VARCHAR(120)   NOT NULL,
    percent  DECIMAL(5, 2),
    amount   DECIMAL(12, 2) NOT NULL,
    CONSTRAINT fk_order_discounts_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_orders_user ON orders (user_id);
CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_discounts_order ON order_discounts (order_id);
